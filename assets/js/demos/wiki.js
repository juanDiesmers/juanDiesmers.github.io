// Demo interactiva de WikiGroupT1
// Simula el recorrido completo de la encuesta de la wiki:
// validación en el navegador (formuverificacion.js) -> POST /submit -> FormController
// -> ApplicationRepository.save (JPA) -> MySQL -> plantilla Resultado de Thymeleaf.
// También muestra el borrado lógico de la entidad (@SQLDelete + @Where).
(function () {
  const EMAIL = /^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$/i;

  function mount(root, { L }) {
    let nextId = 3;
    // Datos de ejemplo para que la tabla no empiece vacía
    const rows = [
      { id: 1, name: 'Ana', apellidos: 'Ejemplo', edad: 21, correo: 'ana@ejemplo.com', descripcion: 'Quiero aprender Spring', semestre: 5, fecha: '2024-04-10', status: 0 },
      { id: 2, name: 'Luis', apellidos: 'Prueba', edad: 23, correo: 'luis@ejemplo.com', descripcion: 'Me interesa el backend', semestre: 7, fecha: '2024-04-12', status: 0 }
    ];
    let showDeleted = false, busy = false;

    const STEPS = [
      ['browser', L('Navegador', 'Browser'), 'formuverificacion.js'],
      ['http', 'HTTP', 'POST /submit'],
      ['ctrl', 'FormController', 'handleSubmitForm()'],
      ['jpa', 'JPA', 'applicationRepository.save()'],
      ['db', 'MySQL', 'INSERT INTO application'],
      ['view', 'Thymeleaf', 'Resultado.html']
    ];

    root.innerHTML = `
      <div class="demo-head"><h4>${L('Pruébalo', 'Try it')}</h4></div>
      <div class="demo-body">
        <p class="hint">${L('Llena la encuesta de la wiki y envíala. Vas a ver cada paso que da el dato: la validación en el navegador, la petición al servidor, el controlador de Spring, el INSERT que genera JPA y la página que devuelve Thymeleaf.',
          'Fill in the wiki survey and send it. You will see every step the data takes: browser validation, the request to the server, the Spring controller, the INSERT generated by JPA and the page Thymeleaf returns.')}</p>
        <div class="demo-split">
          <form data-form novalidate style="display:grid;grid-template-columns:1fr 1fr;gap:.7rem">
            <label class="f">${L('Nombres', 'First name')}<input type="text" name="name" maxlength="120" value="Juan"></label>
            <label class="f">${L('Apellidos', 'Last name')}<input type="text" name="apellidos" maxlength="120"></label>
            <label class="f">${L('Edad', 'Age')}<input type="number" name="edad" value="22"></label>
            <label class="f">${L('Semestre', 'Semester')}<input type="number" name="semestre" value="8"></label>
            <label class="f" style="grid-column:1/-1">${L('Correo', 'Email')}<input type="text" name="correo" value="juan@correo"></label>
            <label class="f" style="grid-column:1/-1">${L('Descripción', 'Description')}<input type="text" name="descripcion" maxlength="120" value="${L('Encuesta de prueba', 'Test survey')}"></label>
            <label class="f">${L('Fecha', 'Date')}<input type="date" name="fecha" value="${new Date().toISOString().slice(0, 10)}"></label>
            <div style="display:flex;align-items:end"><button class="ctl primary" type="submit" style="width:100%">${L('Enviar', 'Send')}</button></div>
            <div data-err style="grid-column:1/-1;font:500 .75rem/1.6 var(--mono);color:#ff8f8f;min-height:1.2em"></div>
          </form>
          <div>
            <ol data-steps style="list-style:none;display:grid;gap:.35rem;margin-bottom:.75rem"></ol>
            <div class="out" data-out style="min-height:8rem"></div>
          </div>
        </div>
        <div class="demo-row" style="margin-top:1.25rem;justify-content:space-between">
          <p class="demo-sub" style="margin:0" data-tt></p>
          <label style="font:500 .75rem var(--mono);color:var(--muted);display:inline-flex;gap:.4rem;align-items:center"><input type="checkbox" data-del> ${L('ver la tabla real (incluye borrados)', 'show the real table (includes deleted)')}</label>
        </div>
        <div style="overflow-x:auto"><table class="cx" data-table></table></div>
      </div>`;
    const $ = q => root.querySelector(q);
    const form = $('[data-form]'), out = $('[data-out]'), err = $('[data-err]');

    function renderSteps(active, done) {
      $('[data-steps]').innerHTML = STEPS.map(([k, t, d], i) => {
        const state = i < done ? 'ok' : i === active ? 'now' : '';
        return `<li style="display:grid;grid-template-columns:1.6rem 7.5rem 1fr;gap:.5rem;align-items:center;font:500 .75rem/1.3 var(--mono);padding:.45rem .6rem;border:1px solid ${state === 'now' ? 'var(--amber)' : 'var(--line)'};border-radius:4px;background:${state === 'now' ? 'var(--amber-dim)' : 'var(--ink)'};color:${state ? 'var(--paper)' : 'var(--muted)'}">
          <span style="color:${state === 'ok' ? 'var(--sage)' : state === 'now' ? 'var(--amber)' : 'var(--muted)'}">${state === 'ok' ? '✓' : i + 1}</span><b style="font-weight:600">${t}</b><span style="color:var(--muted)">${d}</span></li>`;
      }).join('');
    }
    function renderTable() {
      const visible = showDeleted ? rows : rows.filter(r => r.status === 0);
      $('[data-tt]').textContent = showDeleted ? 'SELECT * FROM application' : 'applicationRepository.findAll()  →  @Where(clause = "status = 0")';
      const cols = ['id', 'name', 'apellidos', 'edad', 'correo', 'semestre', 'fecha'].concat(showDeleted ? ['status'] : []);
      $('[data-table]').innerHTML = `<thead><tr>${cols.map(c => `<th>${c}</th>`).join('')}<th></th></tr></thead><tbody>${visible.map(r => `
        <tr style="${r.status ? 'opacity:.5' : ''}">${cols.map(c => `<td>${String(r[c]).replace(/</g, '&lt;')}</td>`).join('')}
        <td>${r.status ? '' : `<button class="link-btn" type="button" data-rm="${r.id}" style="padding:.35rem .5rem">${L('eliminar', 'delete')}</button>`}</td></tr>`).join('')}</tbody>`;
      root.querySelectorAll('[data-rm]').forEach(b => b.onclick = () => softDelete(+b.dataset.rm));
    }
    function softDelete(id) {
      const r = rows.find(x => x.id === id); if (!r) return;
      r.status = 1;
      out.innerHTML = `<span class="dim">applicationRepository.deleteById(${id})</span>\n<span class="dim">-- @SQLDelete reemplaza el DELETE por:</span>\n<span class="am">UPDATE application SET status = 1 WHERE id=${id}</span>\n\n${L('El registro sigue en MySQL, pero findAll() ya no lo devuelve. Marca la casilla para ver la tabla real.', 'The record is still in MySQL, but findAll() no longer returns it. Tick the box to see the real table.')}`;
      renderTable();
    }

    // Validaciones de formuverificacion.js
    function validate(d) {
      const e = {};
      if (!d.name) e.name = L('Nombres: Obligatorio.', 'First name: Required.');
      else if (d.name.length > 100) e.name = L('Nombres: Máximo 100 caracteres.', 'First name: 100 characters max.');
      if (!d.apellidos) e.apellidos = L('Apellidos: Obligatorio.', 'Last name: Required.');
      else if (d.apellidos.length > 100) e.apellidos = L('Apellidos: Máximo 100 caracteres.', 'Last name: 100 characters max.');
      if (d.edad === '' || isNaN(d.edad) || +d.edad < 0 || +d.edad >= 100) e.edad = L('Edad: Obligatorio. Debe ser un número entero entre 0 y 99.', 'Age: Required. Must be a whole number from 0 to 99.');
      if (!EMAIL.test(d.correo)) e.correo = L('Correo: no tiene un formato válido.', 'Email: invalid format.');
      if (!d.descripcion) e.descripcion = L('Descripción: Obligatorio.', 'Description: Required.');
      if (d.semestre === '' || isNaN(d.semestre)) e.semestre = L('Semestre: Obligatorio.', 'Semester: Required.');
      if (!d.fecha) e.fecha = L('Fecha: Obligatorio.', 'Date: Required.');
      return e;
    }
    function paint(e) { form.querySelectorAll('input').forEach(i => { i.style.borderColor = e[i.name] ? '#ff8f8f' : ''; }); }
    form.querySelectorAll('input').forEach(i => i.addEventListener('input', () => {
      const e = validate(Object.fromEntries(new FormData(form)));
      i.style.borderColor = e[i.name] ? '#ff8f8f' : '';
      if (err.textContent) err.innerHTML = Object.values(e).join('<br>');
    }));

    const wait = ms => new Promise(r => setTimeout(r, ms));
    form.addEventListener('submit', async ev => {
      ev.preventDefault(); if (busy) return;
      const d = Object.fromEntries(new FormData(form));
      const e = validate(d);
      renderSteps(0, 0); paint(e);
      if (Object.keys(e).length) {
        err.innerHTML = Object.values(e).join('<br>');
        out.innerHTML = `<span class="bad">${L('La validación del navegador frenó el envío.', 'Browser validation stopped the request.')}</span>\n<span class="dim">${L('El servidor nunca recibe estos datos. Corrige los campos en rojo.', 'The server never receives this data. Fix the fields in red.')}</span>`;
        return;
      }
      err.textContent = ''; busy = true;
      const body = new URLSearchParams(d).toString();
      const id = nextId++;
      const esc = s => String(s).replace(/'/g, "''").replace(/</g, '&lt;');
      const frames = [
        `<span class="ok">${L('Validación correcta', 'Validation passed')}</span>: ${L('todos los campos cumplen las reglas.', 'every field meets the rules.')}`,
        `<span class="am">POST /submit HTTP/1.1</span>\nContent-Type: application/x-www-form-urlencoded\n\n${body.replace(/&/g, '&\n').replace(/</g, '&lt;')}`,
        `<span class="dim">// Spring arma el objeto a partir del formulario</span>\nApplication { name="${esc(d.name)}", apellidos="${esc(d.apellidos)}", edad=${+d.edad}, correo="${esc(d.correo)}", semestre=${+d.semestre}, fecha=${d.fecha} }`,
        `applicationRepository.save(application)\n<span class="dim">// CrudRepository&lt;Application, Long&gt; no necesita implementación: Spring Data la genera</span>`,
        `<span class="sk">insert into application (apellidos, correo, descripcion, edad, fecha, name, semestre)\nvalues ('${esc(d.apellidos)}', '${esc(d.correo)}', '${esc(d.descripcion)}', ${+d.edad}, '${d.fecha}', '${esc(d.name)}', ${+d.semestre})</span>\n<span class="dim">-- id generado: ${id} (GenerationType.IDENTITY)</span>`,
        `return "Resultado";\n\n<span class="ok">Wiki Desarrollo WEB\nDatos registrados con exito!!</span>`
      ];
      for (let i = 0; i < STEPS.length; i++) {
        renderSteps(i, i); out.innerHTML = frames[i];
        if (i === 4) { rows.push({ id, name: d.name, apellidos: d.apellidos, edad: +d.edad, correo: d.correo, descripcion: d.descripcion, semestre: +d.semestre, fecha: d.fecha, status: 0 }); renderTable(); }
        await wait(i === 0 ? 450 : 900);
      }
      renderSteps(-1, STEPS.length); busy = false;
    });
    $('[data-del]').addEventListener('change', e => { showDeleted = e.target.checked; renderTable(); });

    renderSteps(-1, 0); renderTable();
    out.innerHTML = `<span class="dim">${L('Falta el apellido y el correo no es válido: dale a Enviar para ver qué hace la validación, y luego corrígelos.', 'The last name is missing and the email is invalid: press Send to see what validation does, then fix them.')}</span>`;
  }

  window.PortfolioDemos = window.PortfolioDemos || {};
  window.PortfolioDemos.wiki = mount;
})();
